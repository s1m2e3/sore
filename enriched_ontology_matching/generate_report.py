def _load_csv(path: Path) -> list[dict]:
    with open(path, newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def _load_neighbourhood_index(nbr_dir: Path) -> dict[str, list[dict]]:
    """
    Scan nbr_dir for *_coherence.csv files and return a dict mapping
    the domain key stem (e.g. 'auto_V1_V2') to its rows.
    Falls back gracefully if the directory or files are missing.
    """
    index: dict[str, list[dict]] = {}
    if not nbr_dir.is_dir():
        return index
    for f in nbr_dir.glob("*_coherence.csv"):
        key = f.stem.replace("_coherence", "")
        with open(f, newline="", encoding="utf-8") as fh:
            index[key] = list(csv.DictReader(fh))
    return index


def _find_neighbourhood(domain_key: str,
                        nbr_index: dict[str, list[dict]]) -> list[dict]:
    """
    Try to match a combined-CSV domain key to a neighbourhood CSV key.
    Matching is case-insensitive and strips the 'test_' prefix.
    """
    # Build a lower-cased lookup once
    lower_index = {k.lower(): v for k, v in nbr_index.items()}
    for candidate in [
        domain_key,
        domain_key.replace("test_", ""),
    ]:
        hit = lower_index.get(candidate.lower())
        if hit is not None:
            return hit
    return []


