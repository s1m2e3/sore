def _summary_table(by_domain: dict[str, list[dict]],
                   metas: dict[str, dict]) -> str:
    headers = ["Domain", "O1 Entities", "O2 Entities",
               "L1 Matches", "AML", "LogMap", "Both",
               "L2 Equiv", "L2 Subs", "L2 CN-Rel", "Total Rows"]
    rows = []
    totals = [0] * (len(headers) - 1)

    for domain, drows in by_domain.items():
        meta  = metas[domain]
        l1    = [r for r in drows if r["layer"] == "1"]
        l2eq  = [r for r in drows if r["layer"] == "2" and r["layer2_type"] == "Equivalence"]
        l2sub = [r for r in drows if r["layer"] == "2" and r["layer2_type"] == "Subsumption"]
        l2cn  = [r for r in drows if r["layer"] == "2"
                 and r["layer2_type"] not in ("Equivalence", "Subsumption", "None", "")]

        aml   = sum(1 for r in l1 if r["source"] in ("AML", "Both"))
        lm    = sum(1 for r in l1 if r["source"] in ("LogMap", "Both"))
        both  = sum(1 for r in l1 if r["source"] == "Both")

        vals = [meta["entities_a"], meta["entities_b"],
                len(l1), aml, lm, both,
                len(l2eq), len(l2sub), len(l2cn), len(drows)]
        short = domain.replace("test_", "").replace("_", " ")
        rows.append([short] + vals)
        for i, v in enumerate(vals):
            try:
                totals[i] += int(v)
            except (ValueError, TypeError):
                pass

    rows.append(["**TOTAL**"] + [""] * 2 +
                [f"**{totals[i]}**" for i in range(2, len(totals))])
    return _md_table(headers, rows)


# ---------------------------------------------------------------------------
# Cross-domain observations
# ---------------------------------------------------------------------------

def _cross_domain_obs(by_domain: dict[str, list[dict]]) -> str:
    lines = ["\n---\n", "## Cross-Domain Observations\n"]

    # Label distribution across all domains
    all_rows = [r for drows in by_domain.values() for r in drows]
    l2_rows  = [r for r in all_rows if r["layer"] == "2"]

    sem_all: dict[str, int] = defaultdict(int)
    for r in all_rows:
        sem_all[r["semantic_label"]] += 1

    lines.append("### Semantic label distribution across all domains and layers\n")
    dist = sorted(sem_all.items(), key=lambda x: -x[1])
    lines.append(_md_table(["Label", "Count", "% of total"],
                            [[lbl, cnt, f"{100*cnt/len(all_rows):.1f}%"]
                             for lbl, cnt in dist]))
    lines.append("")

    # L1 source breakdown
    lines.append("### Structural matcher coverage per domain\n")
    src_rows = []
    for domain, drows in by_domain.items():
        l1 = [r for r in drows if r["layer"] == "1"]
        aml  = sum(1 for r in l1 if r["source"] in ("AML", "Both"))
        lm   = sum(1 for r in l1 if r["source"] in ("LogMap", "Both"))
        both = sum(1 for r in l1 if r["source"] == "Both")
        short = domain.replace("test_", "").replace("_", " ")
        src_rows.append([short, len(l1), aml, lm, both,
                         f"{100*both/len(l1):.0f}%" if l1 else "—"])
    lines.append(_md_table(
        ["Domain", "Total L1", "AML", "LogMap", "Both", "Overlap %"],
        src_rows))
    lines.append("")

    # CN relation type breakdown across L2
    cn_rel_counts: dict[str, int] = defaultdict(int)
    for r in l2_rows:
        if r["cn_label"] and r["cn_label"] not in ("None", ""):
            cn_rel_counts[r["cn_label"]] += 1
    if cn_rel_counts:
        lines.append("### ConceptNet relation types found (Layer 2)\n")
        rel_dist = sorted(cn_rel_counts.items(), key=lambda x: -x[1])
        lines.append(_md_table(["CN Relation", "Count"],
                                [[rel, cnt] for rel, cnt in rel_dist]))
        lines.append("")

    return "\n".join(lines)


