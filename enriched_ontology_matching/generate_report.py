def _load_domain_meta(domain_key: str) -> dict:
    """
    Return ontology metadata from the test JSON for a given domain key.
    Checks the pairs/ subdirectory first (generated by run_all_pairs.py),
    then falls back to the enriched_ontology_matching root.
    Returns default values if no matching file is found.
    """
    # Check pairs/ subdir first (run_all_pairs.py stores them there)
    test_file = _TEST_DIR / "pairs" / f"{domain_key}.json"
    if not test_file.exists():
        test_file = _TEST_DIR / f"{domain_key}.json"
    meta = {"name_a": domain_key + "_a", "name_b": domain_key + "_b",
            "entities_a": "?", "entities_b": "?",
            "assocs_a": 0, "assocs_b": 0}
    if not test_file.exists():
        return meta
    try:
        data = json.loads(test_file.read_text(encoding="utf-8"))
        ja = data.get("json_a", {})
        jb = data.get("json_b", {})
        meta["name_a"] = ja.get("modelName") or ja.get("ontology_name") or domain_key + "_a"
        meta["name_b"] = jb.get("modelName") or jb.get("ontology_name") or domain_key + "_b"
        meta["entities_a"] = len(ja.get("entities", []))
        meta["entities_b"] = len(jb.get("entities", []))
        meta["assocs_a"]   = len(ja.get("associations", []))
        meta["assocs_b"]   = len(jb.get("associations", []))
    except Exception:
        pass
    return meta


def _tbl_row(*cells: str, widths: list[int] | None = None) -> str:
    if widths:
        cells = [str(c).ljust(w) for c, w in zip(cells, widths)]
    return "| " + " | ".join(str(c) for c in cells) + " |"


def _md_table(headers: list[str], rows: list[list]) -> str:
    col_widths = [max(len(h), max((len(str(r[i])) for r in rows), default=0))
                  for i, h in enumerate(headers)]
    lines = [
        _tbl_row(*headers, widths=col_widths),
        "|" + "|".join("-" * (w + 2) for w in col_widths) + "|",
    ]
    for row in rows:
        lines.append(_tbl_row(*[str(c) for c in row], widths=col_widths))
    return "\n".join(lines)


