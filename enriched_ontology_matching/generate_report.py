def _domain_section(domain: str, rows: list[dict], meta: dict, idx: int,
                    nbr_rows: list[dict] | None = None,
                    lin_ic_rows: list[dict] | None = None,
                    emb_rows: list[dict] | None = None) -> str:
    l1    = [r for r in rows if r["layer"] == "1"]
    l2eq  = [r for r in rows if r["layer"] == "2" and r["layer2_type"] == "Equivalence"]
    l2sub = [r for r in rows if r["layer"] == "2" and r["layer2_type"] == "Subsumption"]
    l2cn  = [r for r in rows if r["layer"] == "2"
             and r["layer2_type"] not in ("Equivalence", "Subsumption", "None", "")]

    aml_only  = sum(1 for r in l1 if r["source"] == "AML")
    lm_only   = sum(1 for r in l1 if r["source"] == "LogMap")
    both      = sum(1 for r in l1 if r["source"] == "Both")

    name_a = meta["name_a"]
    name_b = meta["name_b"]
    ents_a = meta["entities_a"]
    ents_b = meta["entities_b"]

    lines: list[str] = []
    lines.append(f"\n---\n")
    lines.append(f"## Domain {idx}: {name_a} vs {name_b}\n")
    lines.append(f"**Ontology A**: {ents_a} entities &nbsp;|&nbsp; "
                 f"**Ontology B**: {ents_b} entities\n")

    # ── Neighbourhood coherence (if available) ───────────────────────────────
    if nbr_rows:
        lines.append(_neighbourhood_section(nbr_rows))

    # ── Layer 1 ──────────────────────────────────────────────────────────────
    lines.append(f"### Layer 1 — Structural matcher results ({len(l1)} matched pairs)\n")
    lines.append(f"AML: {aml_only + both} &nbsp;|&nbsp; "
                 f"LogMap: {lm_only + both} &nbsp;|&nbsp; "
                 f"Both: {both} &nbsp;|&nbsp; Merged unique: {len(l1)}\n")

    # Semantic label distribution
    sem_counts: dict[str, int] = defaultdict(int)
    for r in l1:
        sem_counts[r["semantic_label"]] += 1
    dist_rows = sorted(sem_counts.items(), key=lambda x: -x[1])
    lines.append(_md_table(["Semantic Label", "Count"],
                            [[lbl, cnt] for lbl, cnt in dist_rows]))
    lines.append("")

    # Non-trivial / low-confidence matches — exclude pairs where entity names
    # are identical (those are structural trivial matches, never interesting).
    non_trivial = [r for r in l1
                   if r["entity_a"].lower() != r["entity_b"].lower()]
    low_conf    = [r for r in l1
                   if r["entity_a"].lower() == r["entity_b"].lower()
                   and float(r["matcher_conf"] or 0) < 0.85]
    interesting = non_trivial + low_conf

    if interesting:
        lines.append("**Non-trivial matches (different entity names):**\n")
        tbl = [[r["entity_a"], r["entity_b"], r["source"],
                r["matcher_conf"], r["semantic_label"],
                r["wup_score"], r.get("max_wup", ""), r.get("avg_wup", "")]
               for r in interesting]
        lines.append(_md_table(
            ["Entity A", "Entity B", "Src", "Conf", "Semantic", "WUP", "MaxWUP", "AvgWUP"],
            tbl,
        ))
        lines.append("")

    # ── Layer 2 equivalences ─────────────────────────────────────────────────
    lines.append(f"### Layer 2 — New equivalence candidates ({len(l2eq)})\n")
    if l2eq:
        tbl = [[r["entity_a"], r["entity_b"], r["semantic_label"],
                r["wup_score"], r.get("max_wup", ""), r.get("avg_wup", ""),
                f"{r['token_a']} / {r['token_b']}"]
               for r in l2eq]
        lines.append(_md_table(
            ["Entity A", "Entity B", "Semantic", "WUP", "MaxWUP", "AvgWUP", "Tokens"],
            tbl,
        ))
    else:
        lines.append("_None found._")
    lines.append("")

    # ── Layer 2 subsumptions ─────────────────────────────────────────────────
    # Sort by max_wup when available, fall back to wup_score
    top_sub = sorted(
        l2sub,
        key=lambda r: float(r.get("max_wup") or r.get("wup_score") or 0),
        reverse=True,
    )[:10]
    lines.append(f"### Layer 2 — Subsumption candidates ({len(l2sub)}, top 10 by MaxWUP)\n")
    if top_sub:
        tbl = [[r["entity_a"], r["entity_b"], r["wn_relation"],
                r["wup_score"], r.get("max_wup", ""), r.get("avg_wup", ""),
                f"{r['token_a']} / {r['token_b']}"]
               for r in top_sub]
        lines.append(_md_table(
            ["Entity A", "Entity B", "WN Relation", "WUP", "MaxWUP", "AvgWUP", "Tokens"],
            tbl,
        ))
    else:
        lines.append("_None found._")
    lines.append("")

    # ── Layer 2 CN-backed relations ──────────────────────────────────────────
    lines.append(f"### Layer 2 — ConceptNet-backed relations ({len(l2cn)})\n")
    if l2cn:
        tbl = [[r["entity_a"], r["entity_b"], r["cn_label"],
                r["wup_score"], r.get("max_wup", ""), r.get("avg_wup", ""),
                f"{r['token_a']} / {r['token_b']}"]
               for r in l2cn]
        lines.append(_md_table(
            ["Entity A", "Entity B", "CN Relation", "WUP", "MaxWUP", "AvgWUP", "Tokens"],
            tbl,
        ))
    else:
        lines.append("_None found._")
    lines.append("")

    # ── Layer 3: Lin-IC final scoring ────────────────────────────────────────
    if lin_ic_rows:
        lines.append(_lin_ic_section(lin_ic_rows))

    # ── Layer 4: Sentence embedding cosine similarity ─────────────────────────
    if emb_rows:
        lines.append(_embedding_section(emb_rows))

    return "\n".join(lines)


