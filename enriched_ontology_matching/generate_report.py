def _neighbourhood_section(nbr_rows: list[dict], threshold: float = 0.5) -> str:
    """
    Render a Neighbourhood Coherence subsection from the coherence CSV rows.
    """
    if not nbr_rows:
        return ""

    supported = [r for r in nbr_rows
                 if float(r.get("coherence_sym") or 0) >= threshold
                 and (int(r.get("n_nbrs_a") or 0) > 0
                      and int(r.get("n_nbrs_b") or 0) > 0)]
    isolated_a = [r for r in nbr_rows if int(r.get("n_nbrs_a") or 0) == 0]
    isolated_b = [r for r in nbr_rows if int(r.get("n_nbrs_b") or 0) == 0]
    low = [r for r in nbr_rows
           if float(r.get("coherence_sym") or 0) < threshold
           and int(r.get("n_nbrs_a") or 0) > 0
           and int(r.get("n_nbrs_b") or 0) > 0]

    lines: list[str] = []
    lines.append(f"### Layer 0 — Neighbourhood Coherence "
                 f"({len(nbr_rows)} matched pairs analysed)\n")
    lines.append(
        f"Threshold: {threshold} &nbsp;|&nbsp; "
        f"**Supported** (sym >= {threshold}): **{len(supported)}** &nbsp;|&nbsp; "
        f"Low coherence: {len(low)} &nbsp;|&nbsp; "
        f"Isolated in A: {len(isolated_a)} &nbsp;|&nbsp; "
        f"Isolated in B: {len(isolated_b)}\n"
    )

    if supported:
        lines.append("**Neighbourhood-supported matches** "
                     "(name match confirmed by local graph context):\n")
        tbl = []
        for r in sorted(supported,
                        key=lambda x: float(x.get("coherence_sym") or 0),
                        reverse=True):
            tbl.append([
                r["entity_a"], r["entity_b"],
                r.get("semantic_label", ""),
                r.get("coherence_a2b", ""), r.get("coherence_b2a", ""),
                r.get("coherence_sym", ""),
                r.get("avg_best_a2b", ""), r.get("avg_best_b2a", ""),
                r.get("verb_coherence", ""),
                r.get("best_pairs", "")[:60],
            ])
        lines.append(_md_table(
            ["Entity A", "Entity B", "Semantic",
             "Coh_A2B", "Coh_B2A", "Coh_sym",
             "AvgBest_A2B", "AvgBest_B2A", "VerbCoh", "Best neighbour pairs"],
            tbl,
        ))
        lines.append("")

    if low:
        lines.append("**Low-coherence matches** "
                     "(name match but neighbourhood disagrees):\n")
        tbl = []
        for r in sorted(low,
                        key=lambda x: float(x.get("coherence_sym") or 0)):
            tbl.append([
                r["entity_a"], r["entity_b"],
                r.get("semantic_label", ""),
                r.get("coherence_sym", ""),
                r.get("n_nbrs_a", ""), r.get("n_nbrs_b", ""),
                r.get("best_pairs", "")[:50],
            ])
        lines.append(_md_table(
            ["Entity A", "Entity B", "Semantic", "Coh_sym",
             "Nbrs_A", "Nbrs_B", "Best neighbour pairs"],
            tbl,
        ))
        lines.append("")

    if isolated_a:
        ent_list = ", ".join(r["entity_a"] for r in isolated_a[:15])
        if len(isolated_a) > 15:
            ent_list += f" … (+{len(isolated_a)-15} more)"
        lines.append(f"**Isolated in A** (no graph edges — name-only matches): "
                     f"{ent_list}\n")

    return "\n".join(lines)


